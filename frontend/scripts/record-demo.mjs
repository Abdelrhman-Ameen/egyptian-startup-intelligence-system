import { chromium } from 'playwright';
import { copyFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const url = process.argv[2] || 'http://127.0.0.1:8001';
const output = fileURLToPath(new URL('../../tmp/demo-recording/', import.meta.url));
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true, channel: process.env.CI ? undefined : 'msedge' });
const context = await browser.newContext({ viewport: { width: 1440, height: 900 }, recordVideo: { dir: output, size: { width: 1440, height: 900 } } });
const page = await context.newPage();
await page.goto(url);
await page.locator('.metric-card').first().getByText('340,000', { exact: false }).waitFor();
await page.waitForTimeout(1100);
await page.getByLabel('Reduce payments').fill('25');
await page.getByRole('button', { name: 'Compare cash paths' }).click();
await page.locator('.metric-card').first().getByText('700,000', { exact: false }).waitFor();
await page.waitForTimeout(1500);
await page.getByRole('button', { name: 'Financial ML lab' }).click();
await page.getByLabel('Historical example').locator('option').nth(5).waitFor({ state: 'attached' });
await page.getByLabel('Historical example').selectOption({ index: 3 });
await page.getByRole('button', { name: 'Evaluate example' }).click();
await page.getByText('Observed historical outcome').waitFor();
await page.waitForTimeout(1800);
await page.getByRole('button', { name: '64 ratios Full schema' }).click();
await page.getByRole('button', { name: 'Evaluate example' }).click();
await page.getByText('Observed historical outcome').waitFor();
await page.waitForTimeout(1800);
await page.getByRole('button', { name: 'Methodology' }).click();
await page.locator('.comparison-panel').scrollIntoViewIfNeeded();
await page.waitForTimeout(1600);
await page.locator('.stress-panel').scrollIntoViewIfNeeded();
await page.waitForTimeout(1800);
await page.getByRole('button', { name: 'Cash planner' }).click();
await page.locator('.metric-card').first().getByText('340,000', { exact: false }).waitFor();
await page.waitForTimeout(1200);
const video = page.video();
await context.close();
const destination = fileURLToPath(new URL('../../tmp/ventureguard-demo.webm', import.meta.url));
await copyFile(await video.path(), destination);
await browser.close();
console.log(destination);
